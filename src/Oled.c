/*********************I2C HARDWARE PROTOCOL ***********************/
static void I2C1_Init(void){
    RCC->APB2ENR |= RCC_APB2ENR_IOPBEN | RCC_APB2ENR_AFIOEN;
    RCC->APB1ENR |= RCC_APB1ENR_I2C1EN;

    //PB6(SCL) & PB7(SDA) Alternate Function Open-Drain, 50MHz
    GPIOB->CRL &= ~(0xF << 24); //1111, reset bit PB6
    GPIOB->CRL |= (0xF << 24);

    GPIOB->CRL &= ~(0xF << 28); //1111, reset bit PB7
    GPIOB->CRL |= (0xF << 28);

    //Reset I2C1
    I2C1->CR1 |= (1 << 15U); // SWRST = 1
    I2C1->CR1 &= ~(1 << 15U); // SWRST = 0, end reset

    //Speed
    I2C1->CR2 &= ~0x3F;
    I2C1->CR2 |= 36; //FREQ[5:0] = 100100 = 36Mhz = clock APB1
    I2C1->CCR &= ~0xFFF;
    I2C1->CCR |= 180; //CCR = PLCK1 / (2 * SCL) = (36Mhz / (2 * 100kHz) = 180)
    I2C1->TRISE &= ~0x3F;
    I2C1->TRISE |= 37; //FREQ + 1

    //EN I2C1
    I2C1->CR1 |= (1 << 0U); //PE
}

static void I2C1_Start(void){
    I2C1->CR1 |= (1 << 8U); //START
    while (!(I2C1->SR1 & (1 << 0U))); //wait for SB
}

static void I2C1_SendAddress(uint8_t addr){
    I2C1->DR = addr;
    while(!(I2C1->SR1 & (1 << 1U)));
    (void)I2C1->SR1;
    (void)I2C1->SR2;
}

static void I2C1_Write(uint8_t data){
    while(!(I2C1->SR1 & (1 << 7U)));
    I2C1->DR = data;
}

static void I2C1_Stop(void){
    while(!(I2C1->SR1 & (1 << 7U)));
    while(!(I2C1->SR1 & (1 << 2U)));
    I2C1->CR1 |= (1 << 9U); //STOP
}

/****************************************SSD1306 ******************************/
static void OLED_WriteCmd(uint8_t cmd){
    I2C1_Start();
    I2C1_SendAddress(OLED_I2C_ADDR);
    I2C1_Write(0x00); //Co = 0, DC = 0
    I2C1_Write(cmd);
    I2C1_Stop();
} //command

static void OLED_WriteData(uint8_t data){
    I2C1_Start();
    I2C1_SendAddress(OLED_I2C_ADDR);
    I2C1_Write(0x40); //Co = 0, DC = 1
    I2C1_Write(data);
    I2C1_Stop();
} //data

void OLED_Init(void){
    I2C1_Init();

    OLED_WriteCmd(0xAE); //Display OFF
    OLED_WriteCmd(0x20); OLED_WriteCmd(0x20); //Page Addressing Mode
    OLED_WriteCmd(0x8D); OLED_WriteCmd(0x14); // Enable Charge Pump
    OLED_WriteCmd(0xAF); // Display ON

    OLED_Clear();
}

void OLED_SetCursor(uint8_t x, uint8_t y){
    OLED_WriteCmd(0xB0 + y); //Set row (hang ngang)
    OLED_WriteCmd(0x00 | (x & 0x0F)); //Low collumn
    OLED_WriteCmd(0x10 | ((x >> 4) & 0x0F)); //High collumn
}

void OLED_Clear(void){
    for(uint8_t y = 0; y < 8; y++){
        OLED_SetCursor(0, y);
        for(uint8_t x = 0; x < 128; x++){
            OLED_WriteData(0x00);
        }
    }
}


static void OLED_PrintChar(char c){
    if (c < 32 || c > 90) c = 32;
    for (uint8_t i = 0; i < 5; i++){
        OLED_WriteData(Font5x8[c - 32][i]);
    }
    OLED_WriteData(0x00);
}

void OLED_PrintString(char *str){
    while(*str){
        OLED_PrintChar(*str++);
    }
}

void FloatToString(float value, char* buf, char* prefix) {
    int nguyen = (int)value;
    int thap_phan = (int)((value - nguyen) * 10);
    if (thap_phan < 0) thap_phan = -thap_phan;
    
    int idx = 0;
    
    // Copy prefix
    while(*prefix) buf[idx++] = *prefix++;
    
    buf[idx++] = (nguyen / 10) + '0';
    buf[idx++] = (nguyen % 10) + '0';
    buf[idx++] = '.';
    buf[idx++] = thap_phan + '0';
    buf[idx++] = '\0';
}
